// A pack as an eve agent app: <outDir>/<pack>/ with a package.json naming eve (how eve finds its
// project root) and agent/ holding agent.ts, instructions.md, skills/, tools/, the channel and the
// sandbox. Roles and packs are static, so every agent is compiled and `eve build` run at image
// build (build.ts); a run only starts the built server and sends the prompt. The model is the
// engine's, read when the server starts (agent/model.ts), so one build serves every eve engine.
import { type Access, type AgentPack } from "@hardness/contracts";
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

import { LUNA_TOOLS } from "../../core/luna-tools.ts";
import { EVE_TOOL_NAMES, factoryRules } from "../../core/render.ts";
import { readRole } from "../../core/roles.ts";

export interface CompileOptions {
  /** The factory package: roles/, plugin/skills/ and src/ are read from here. */
  factoryRoot: string;
  /** Where the agent apps go, one folder per pack. Inside the factory, so they resolve eve. */
  outDir: string;
  /** "engine" (the default) runs the model the runner names; "scripted" the conformance fake. */
  model?: "engine" | "scripted";
}

/** The eve version the apps declare; eve finds a project by a package.json that depends on it. */
const EVE_VERSION = "1.0.0-rc.1";
const GENERATED = "Generated by factory/src/runtimes/eve/compile.ts; do not edit.";
/** The guarded tools, served from agent/tools.ts; the rest are eve's own. */
const GUARDED = new Set(["bash", "read_file", "write_file", "glob", "grep", "web_fetch"]);

/** A pack's access as eve's tool names: the shell only with commands to run, the file tools by
 *  read and write, web_fetch for the web, then the luna tools. Subagents are not mapped yet. */
export function eveTools(access: Access): string[] {
  return [
    ...(access.commands.length > 0 ? ["bash"] : []),
    ...(access.read ? ["read_file", "glob", "grep"] : []),
    ...(access.write ? ["write_file"] : []),
    ...(access.web ? ["web_fetch"] : []),
    ...access.luna,
  ];
}

/** An import path from `from` to the factory source at `to`, POSIX-style and dot-led. */
const importPath = (from: string, to: string): string => {
  const rel = relative(from, to).split("\\").join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
};

/** The tokens a run may spend per turn it was given; past them eve stops starting model calls. */
export const tokenBudgetPerTurn = { input: 60_000, output: 8_000 };

/** The usage cap eve stops at, for the turns the runner gives this run (LUNA_EVE_MAX_TURNS, the
 *  stage input's limit; the pack's own as a fallback). The runner's model-call cap (run.ts) is the
 *  turn limit itself. */
const usageLimit = (pack: AgentPack): string =>
  `({ window }) => { const turns = Number(process.env.LUNA_EVE_MAX_TURNS) || ${pack.maxTurns}; return window.inputTokens - window.cacheReadTokens >= turns * ${tokenBudgetPerTurn.input} || window.outputTokens >= turns * ${tokenBudgetPerTurn.output}; }`;

/** Every file of the pack's agent app but its skills, by path relative to the app. */
export function agentFiles(pack: AgentPack, options: CompileOptions): Record<string, string> {
  if (!pack.agent) throw new Error(`pack ${pack.id} has no agent to compile`);
  const app = join(options.outDir, pack.id);
  const lib = join(options.factoryRoot, "src", "runtimes", "eve");
  const fromAgent = (file: string) => importPath(join(app, "agent"), join(lib, file));
  const fromTools = (file: string) => importPath(join(app, "agent", "tools"), join(lib, file));

  const model =
    options.model === "scripted"
      ? { line: `import { scriptedModel } from "${fromAgent("fake.ts")}";`, expr: "scriptedModel()" }
      : { line: `import { stageModel } from "${fromAgent("agent/model.ts")}";`, expr: "stageModel()" };
  const agent = [
    `// ${GENERATED} Pack ${pack.id}, role ${pack.agent}.`,
    `import { defineAgent } from "eve";`,
    model.line,
    "",
    "export default defineAgent({",
    `  model: ${model.expr},`,
    `  reasoning: "${pack.effort}",`,
    "  defaultTools: false,",
    `  limits: { sessionUsage: ${usageLimit(pack)} },`,
    "});",
    "",
  ].join("\n");

  const rolesDir = join(options.factoryRoot, "roles");
  const addendumFile = join(rolesDir, pack.agent, "eve.md");
  const addendum = existsSync(addendumFile) ? `\n${readFileSync(addendumFile, "utf8").trimEnd()}\n` : "";
  // Role bodies call the luna tools by their Claude names (`mcp__luna__step`); eve serves them bare.
  const body = readRole(rolesDir, pack.agent).body.trimEnd().replaceAll("mcp__luna__", "");
  const instructions = `${body}\n\n${factoryRules(EVE_TOOL_NAMES)}\n${addendum}`;

  const tools = Object.fromEntries(
    eveTools(pack.access).map((tool) => {
      const body = GUARDED.has(tool)
        ? `export { ${tool} as default } from "${fromTools("agent/tools.ts")}";\n`
        : tool in LUNA_TOOLS
          ? `import { lunaTool } from "${fromTools("agent/tools.ts")}";\n\nexport default lunaTool("${tool}");\n`
          : `export { default } from "eve/tools/${tool}";\n`;
      return [`agent/tools/${tool}.ts`, body];
    }),
  );

  return {
    "package.json": `${JSON.stringify({ name: `luna-${pack.id.replaceAll("_", "-")}`, private: true, type: "module", description: GENERATED, dependencies: { eve: EVE_VERSION } }, null, 2)}\n`,
    "agent/agent.ts": agent,
    "agent/instructions.md": instructions,
    "agent/channels/eve.ts": `export { default } from "${importPath(join(app, "agent", "channels"), join(lib, "agent", "channel.ts"))}";\n`,
    "agent/sandbox.ts": `export { default, environment } from "${fromAgent("sandbox.ts")}";\n`,
    ...tools,
  };
}

/** Writes the pack's agent app afresh, skills included when its access has them; returns its folder. */
export function compileAgent(pack: AgentPack, options: CompileOptions): string {
  const app = join(options.outDir, pack.id);
  rmSync(join(app, "agent"), { recursive: true, force: true });
  for (const [rel, body] of Object.entries(agentFiles(pack, options))) {
    mkdirSync(dirname(join(app, rel)), { recursive: true });
    writeFileSync(join(app, rel), body);
  }
  if (pack.access.skills) {
    for (const skill of pack.skills) cpSync(join(options.factoryRoot, "plugin", "skills", skill), join(app, "agent", "skills", skill), { recursive: true });
  }
  return app;
}
